constexpr std::uint16_t kKeyboard = 0x07;
constexpr std::uint16_t kConsumer = 0x0C;

constexpr KeyCode key(std::uint16_t usage, std::uint16_t scan) {
    return {.usage = {.page = kKeyboard, .usage = usage},
            .scan = {.code = scan, .extended = false}};
}

constexpr KeyCode extended(std::uint16_t usage, std::uint16_t scan) {
    return {.usage = {.page = kKeyboard, .usage = usage}, .scan = {.code = scan, .extended = true}};
}

constexpr KeyCode media(std::uint16_t usage, std::uint16_t scan) {
    return {.usage = {.page = kConsumer, .usage = usage}, .scan = {.code = scan, .extended = true}};
}

