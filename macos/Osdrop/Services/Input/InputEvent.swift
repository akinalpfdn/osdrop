import CoreGraphics
import Foundation

/// A key identified by its USB HID usage, the platform-neutral key identity Osdrop sends between
/// computers. Ordinary keys use the keyboard page; media keys use the consumer page.
struct HIDKey: Hashable, Sendable {
    static let keyboardPage: UInt16 = 0x07
    static let consumerPage: UInt16 = 0x0C

    let page: UInt16
    let usage: UInt16

    static func keyboard(_ usage: UInt16) -> HIDKey {
        HIDKey(page: keyboardPage, usage: usage)
    }

    static func consumer(_ usage: UInt16) -> HIDKey {
        HIDKey(page: consumerPage, usage: usage)
    }

    /// Page and usage in hexadecimal, for diagnostics only.
    var hexDescription: String {
        String(format: "%02X:%04X", page, usage)
    }
}

enum KeyAction: Sendable, Equatable {
    case down
    case up
    /// A key-down generated by the controller's key repeat while the key stays held.
    case repeated
}

enum MouseButton: Hashable, Sendable {
    case left
    case right
    case middle
    /// Buttons 3 and above, numbered as CoreGraphics numbers them.
    case other(Int)

    init(number: Int) {
        switch number {
        case 0: self = .left
        case 1: self = .right
        case 2: self = .middle
        default: self = .other(number)
        }
    }

    var number: Int {
        switch self {
        case .left: 0
        case .right: 1
        case .middle: 2
        case .other(let number): number
        }
    }
}

enum ScrollUnit: Sendable, Equatable {
    /// Notched wheels: lines, possibly fractional with smooth scrolling.
    case line
    /// Trackpads and continuous wheels: points.
    case pixel
}

enum ScrollPhase: Sendable, Equatable {
    case none
    case mayBegin
    case began
    case changed
    case ended
    case cancelled
}

enum MomentumPhase: Sendable, Equatable {
    case none
    case began
    case changed
    case ended
}

struct ScrollDelta: Sendable, Equatable {
    var x: Double
    var y: Double
    var unit: ScrollUnit
    var phase: ScrollPhase = .none
    var momentum: MomentumPhase = .none
}

/// One unit of input, as captured on the controller and injected on an endpoint.
enum InputEvent: Sendable, Equatable {
    /// Relative pointer movement in points, after the controller's own pointer acceleration.
    case pointerMoved(dx: Double, dy: Double)
    case button(MouseButton, isDown: Bool)
    case scroll(ScrollDelta)
    case key(HIDKey, KeyAction)
}

struct CapturedInput: Sendable, Equatable {
    let event: InputEvent
    /// Nanoseconds since the system started, as CoreGraphics stamps events.
    let timestamp: UInt64
    /// Where the cursor was, in global display points (top left origin); held in place while
    /// the input is captured.
    let location: CGPoint
    /// `DispatchTime` uptime nanoseconds when the event tap received it, for latency: event
    /// timestamps do not use one unit on every Mac.
    let tapTime: UInt64

    init(event: InputEvent, timestamp: UInt64, location: CGPoint = .zero, tapTime: UInt64 = 0) {
        self.event = event
        self.timestamp = timestamp
        self.location = location
        self.tapTime = tapTime
    }
}
