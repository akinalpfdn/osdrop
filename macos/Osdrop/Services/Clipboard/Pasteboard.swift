import AppKit

/// The pasteboard types the shared clipboard reads and writes, and the markers that keep a copy
/// on this Mac.
enum PasteboardTypes {
    static let text = NSPasteboard.PasteboardType.string.rawValue
    static let rtf = NSPasteboard.PasteboardType.rtf.rawValue
    static let html = NSPasteboard.PasteboardType.html.rawValue
    static let png = NSPasteboard.PasteboardType.png.rawValue
    static let tiff = NSPasteboard.PasteboardType.tiff.rawValue
    static let shared = [text, rtf, html, png, tiff]

    /// Copies carrying any of these never leave the Mac: passwords and other concealed or
    /// transient data (nspasteboard.org conventions and the password managers that predate them).
    static let sensitive: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "com.typeit4me.clipping",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
        "net.antelle.keeweb",
    ]
}

/// What a copy on this Mac holds in the shared formats.
struct PasteboardSnapshot: Equatable, Sendable {
    /// The shared formats' data, by pasteboard type.
    var data: [String: Data]
    var fileURLs: [URL]
}

/// What the shared clipboard writes for another computer's copy.
struct PasteboardContent: Equatable, Sendable {
    var data: [String: Data]
    var fileURLs: [URL]
}

@MainActor
protocol PasteboardAccess: AnyObject, Sendable {
    /// Grows with every change to the pasteboard.
    var changeCount: Int { get }
    /// Every type on the pasteboard, read before any data so a concealed copy is never read.
    func types() -> Set<String>
    func read() -> PasteboardSnapshot
    /// Replaces the pasteboard's contents; the change count that leaves.
    func write(_ content: PasteboardContent) -> Int
}

/// The general pasteboard.
@MainActor
final class GeneralPasteboard: PasteboardAccess {
    private let pasteboard = NSPasteboard.general

    var changeCount: Int { pasteboard.changeCount }

    func types() -> Set<String> {
        Set((pasteboard.types ?? []).map(\.rawValue))
    }

    func read() -> PasteboardSnapshot {
        var data: [String: Data] = [:]
        let available = types()
        for type in PasteboardTypes.shared where available.contains(type) {
            data[type] = pasteboard.data(forType: NSPasteboard.PasteboardType(type))
        }
        let urls =
            pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL]
            ?? []
        return PasteboardSnapshot(data: data, fileURLs: urls)
    }

    func write(_ content: PasteboardContent) -> Int {
        pasteboard.clearContents()
        // One item per file, as Finder writes a copy; the other formats go on the first item.
        var items = content.fileURLs.map { url in
            let item = NSPasteboardItem()
            item.setString(url.absoluteString, forType: .fileURL)
            return item
        }
        if items.isEmpty {
            items = [NSPasteboardItem()]
        }
        for (type, data) in content.data {
            items[0].setData(data, forType: NSPasteboard.PasteboardType(type))
        }
        pasteboard.writeObjects(items)
        return pasteboard.changeCount
    }
}
