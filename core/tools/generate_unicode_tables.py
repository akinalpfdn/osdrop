#!/usr/bin/env python3
"""Writes the tables core's NFC normalization uses (core/src/transfer/unicode_tables.inc).

The data comes from Python's unicodedata, so the Unicode version is the one of the Python that
runs this script; scripts/lint.sh runs it with a pinned Python (uvx --python 3.13) and --check.

    uvx --python 3.13 python core/tools/generate_unicode_tables.py          # write
    uvx --python 3.13 python core/tools/generate_unicode_tables.py --check  # what lint runs
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

OUTPUT = Path(__file__).resolve().parent.parent / "src/transfer/unicode_tables.inc"
VECTORS = Path(__file__).resolve().parent.parent / "tests/data/nfc_vectors.txt"
HANGUL_FIRST, HANGUL_LAST = 0xAC00, 0xD7A3


def code_points() -> range:
    return range(0x110000)


def canonical_decompositions() -> dict[int, list[int]]:
    """One level of canonical decomposition; compatibility mappings ("<tag> ...") are skipped."""
    table = {}
    for cp in code_points():
        if HANGUL_FIRST <= cp <= HANGUL_LAST:
            continue  # algorithmic
        mapping = unicodedata.decomposition(chr(cp))
        if mapping and not mapping.startswith("<"):
            table[cp] = [int(part, 16) for part in mapping.split()]
    return table


def combining_classes() -> list[tuple[int, int]]:
    return [(cp, unicodedata.combining(chr(cp))) for cp in code_points() if unicodedata.combining(chr(cp))]


def compositions(decompositions: dict[int, list[int]]) -> list[tuple[int, int, int]]:
    """Primary composites: pairs that NFC composes back (exclusions and singletons drop out)."""
    pairs = []
    for cp, parts in decompositions.items():
        if len(parts) == 2 and unicodedata.normalize("NFC", chr(parts[0]) + chr(parts[1])) == chr(cp):
            pairs.append((parts[0], parts[1], cp))
    return sorted(pairs)


def simple_lowercase() -> list[tuple[int, int]]:
    """Code points whose lowercase is one other code point: the folding used to find names that
    a case-insensitive file system (APFS, NTFS) treats as the same."""
    table = []
    for cp in code_points():
        if 0xD800 <= cp <= 0xDFFF:
            continue
        lower = chr(cp).lower()
        if len(lower) == 1 and ord(lower) != cp:
            table.append((cp, ord(lower)))
    return table


def render() -> str:
    decompositions = canonical_decompositions()
    lines = [
        "// Generated by core/tools/generate_unicode_tables.py from Python's unicodedata,",
        f"// Unicode {unicodedata.unidata_version}. Do not edit.",
        "// NOLINTBEGIN",
        "",
        f'inline constexpr const char* kUnicodeVersion = "{unicodedata.unidata_version}";',
        "",
        "// Canonical decompositions, one level: code point, first index and length in kDecomposed.",
        "inline constexpr Decomposition kDecompositions[] = {",
    ]
    flat: list[int] = []
    for cp in sorted(decompositions):
        parts = decompositions[cp]
        lines.append(f"    {{0x{cp:X}, {len(flat)}, {len(parts)}}},")
        flat.extend(parts)
    lines.append("};")
    lines.append("")
    lines.append("inline constexpr char32_t kDecomposed[] = {")
    for start in range(0, len(flat), 8):
        lines.append("    " + " ".join(f"0x{cp:X}," for cp in flat[start:start + 8]))
    lines.append("};")
    lines.append("")
    lines.append("// Non-zero canonical combining classes.")
    lines.append("inline constexpr CombiningClass kCombiningClasses[] = {")
    for cp, ccc in combining_classes():
        lines.append(f"    {{0x{cp:X}, {ccc}}},")
    lines.append("};")
    lines.append("")
    lines.append("// Primary composites, sorted by (first, second).")
    lines.append("inline constexpr Composition kCompositions[] = {")
    for first, second, composite in compositions(decompositions):
        lines.append(f"    {{0x{first:X}, 0x{second:X}, 0x{composite:X}}},")
    lines.append("};")
    lines.append("")
    lines.append("// Simple lowercase mappings, sorted by code point.")
    lines.append("inline constexpr CaseMapping kLowercase[] = {")
    for cp, lower in simple_lowercase():
        lines.append(f"    {{0x{cp:X}, 0x{lower:X}}},")
    lines.append("};")
    lines.append("")
    lines.append("// NOLINTEND")
    return "\n".join(lines) + "\n"


def vectors() -> str:
    """Strings mixed from the hard cases, with the NFC Python computes: the oracle for the C++
    tests. Each line: input and its NFC as UTF-8 hex, tab separated."""
    import random

    pools = [
        list(range(0x41, 0x5B)) + list(range(0x61, 0x7B)),  # ASCII letters
        list(range(0x300, 0x370)),  # combining diacritics
        list(range(0xC0, 0x180)),  # precomposed Latin
        list(range(0x1100, 0x1200)) + [0xAC00, 0xAC01, 0xB098, 0xD7A3],  # jamo and syllables
        [0x958, 0x95F, 0x93C, 0x915, 0x2ADC, 0xFB1D, 0x2126, 0x212B, 0xF900, 0x1D15E],  # exclusions, singletons
        list(range(0x1E00, 0x1F00)) + list(range(0x1F00, 0x2000)),  # Latin extended additional, Greek
        [0x5B0, 0x5B1, 0x5BC, 0x5C1, 0x5D1, 0x5E9, 0x0FB2, 0x0F71, 0x0F80, 0x0F72],  # Hebrew, Tibetan
        [0x11131, 0x11132, 0x11127, 0x1E4EC, 0x1F600, 0x1F3FD],  # astral marks and emoji
    ]
    rng = random.Random(1534)
    lines = [f"# NFC test vectors, Unicode {unicodedata.unidata_version}. Generated; do not edit."]
    for _ in range(3000):
        text = "".join(chr(rng.choice(rng.choice(pools))) for _ in range(rng.randint(1, 8)))
        nfc = unicodedata.normalize("NFC", text)
        lines.append(f"{text.encode().hex()}\t{nfc.encode().hex()}")
    return "\n".join(lines) + "\n"


def main() -> int:
    outputs = {OUTPUT: render(), VECTORS: vectors()}
    if "--check" in sys.argv[1:]:
        stale = [path for path, content in outputs.items()
                 if not path.exists() or path.read_text(encoding="utf-8") != content]
        for path in stale:
            print(f"{path.name} is out of date; run core/tools/generate_unicode_tables.py", file=sys.stderr)
        if stale:
            return 1
        print(f"Unicode tables up to date (Unicode {unicodedata.unidata_version}).")
        return 0
    for path, content in outputs.items():
        path.write_text(content, encoding="utf-8")
        print(f"Wrote {path.name} (Unicode {unicodedata.unidata_version}).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
